/**
 * PhishSim AI — Risk Briefing Controller (Part 7)
 * Calm, authoritative Monday morning executive briefing.
 * Ensures strict XSS protection: all untrusted data handled via textContent.
 */

(function () {
  'use strict';

  const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  // ── 1. Figure Counting Animation (600ms Eased) ──────────────────────────
  function easeOutCubic(t) {
    return 1 - Math.pow(1 - t, 3);
  }

  function animateFigure(elementId, targetValue, suffix = '%') {
    const el = document.getElementById(elementId);
    if (!el) return;

    if (prefersReducedMotion) {
      el.textContent = targetValue.toFixed(1).replace('.0', '') + suffix;
      return;
    }

    const duration = 600;
    const start = performance.now();

    function frame(now) {
      const elapsed = now - start;
      const progress = Math.min(elapsed / duration, 1);
      const eased = easeOutCubic(progress);
      const current = eased * targetValue;
      el.textContent = current.toFixed(1).replace('.0', '') + suffix;

      if (progress < 1) {
        requestAnimationFrame(frame);
      } else {
        el.textContent = targetValue.toFixed(1).replace('.0', '') + suffix;
      }
    }

    requestAnimationFrame(frame);
  }

  // ── 2. Copy Executive Summary ──────────────────────────────────────────
  window.copyBriefingSummary = function () {
    const headline = document.querySelector('.bf-headline')?.textContent?.trim() || '';
    const reportRate = document.getElementById('bf-num-report')?.textContent?.trim() || '—';
    const clickRate = document.getElementById('bf-num-click')?.textContent?.trim() || '—';
    const domain = document.querySelector('.bf-domain-name')?.textContent?.trim() || 'Company';
    const dateCovered = document.querySelector('.bf-date-covered')?.textContent?.trim() || '';

    const summaryText = [
      `RISK BRIEFING · ${domain.toUpperCase()}`,
      `Period: ${dateCovered}`,
      ``,
      `Headline: ${headline}`,
      ``,
      `Key Metrics:`,
      `• Report Rate: ${reportRate} (Employees who flagged threats)`,
      `• Click Rate:  ${clickRate} (Simulated link interactions)`,
      ``,
      `Generated by PhishSim AI Risk Briefing`
    ].join('\n');

    navigator.clipboard.writeText(summaryText).then(() => {
      const btn = document.getElementById('bf-copy-summary-btn');
      if (btn) {
        const originalText = btn.innerHTML;
        btn.innerHTML = `<i class="ti ti-check"></i> <span>Copied</span>`;
        setTimeout(() => {
          btn.innerHTML = originalText;
        }, 2000);
      }
    }).catch(err => {
      console.error('Failed to copy summary:', err);
    });
  };

  // ── 3. Check Domain Email Authentication (Inline Action) ───────────────
  window.checkDomainAuthInline = async function () {
    const btn = document.getElementById('bf-check-auth-btn');
    const resultBox = document.getElementById('bf-auth-result');
    if (!btn || !resultBox) return;

    btn.disabled = true;
    const originalText = btn.innerHTML;
    btn.innerHTML = `<i class="ti ti-loader-2 spin"></i> Checking DNS...`;

    try {
      const csrfToken = document.querySelector('meta[name="csrf-token"]')?.getAttribute('content') || '';
      const response = await fetch('/api/remediate/domain-lockdown', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'X-CSRFToken': csrfToken
        }
      });
      const data = await response.json();

      btn.disabled = false;
      btn.innerHTML = originalText;
      resultBox.classList.add('is-visible');

      if (data.success) {
        const spfStatus = data.spf_is_enforced ? 'Pass (Enforced)' : 'Action needed';
        const dmarcStatus = data.dmarc_is_enforced ? 'Pass (Enforced)' : 'Action needed';
        const verdict = data.status === 'secure' ? 'Fully Hardened' : 'Vulnerable to Spoofing';

        resultBox.textContent = `SPF: ${data.spf_status} (${spfStatus}) · DMARC: ${data.dmarc_status} (${dmarcStatus}) · Posture: ${verdict}`;
      } else {
        resultBox.textContent = data.error || 'DNS authentication check failed.';
      }
    } catch (e) {
      btn.disabled = false;
      btn.innerHTML = originalText;
      resultBox.classList.add('is-visible');
      resultBox.textContent = 'DNS check failed: ' + e.message;
    }
  };

  // ── 4. Decoy Mailbox Slide-Over Drawer ──────────────────────────────────
  window.openDecoyDrawer = function () {
    const overlay = document.getElementById('bf-decoy-overlay');
    if (overlay) {
      overlay.classList.add('is-open');
      overlay.setAttribute('aria-hidden', 'false');
      fetchDecoyList();
    }
  };

  window.closeDecoyDrawer = function () {
    const overlay = document.getElementById('bf-decoy-overlay');
    if (overlay) {
      overlay.classList.remove('is-open');
      overlay.setAttribute('aria-hidden', 'true');
    }
  };

  window.switchDecoyDrawerTab = function (tabName) {
    const tabListBtn = document.getElementById('bf-tab-btn-list');
    const tabNewBtn = document.getElementById('bf-tab-btn-new');
    const panelList = document.getElementById('bf-tab-panel-list');
    const panelNew = document.getElementById('bf-tab-panel-new');

    if (tabName === 'list') {
      tabListBtn?.classList.add('is-active');
      tabNewBtn?.classList.remove('is-active');
      if (panelList) panelList.style.display = 'block';
      if (panelNew) panelNew.style.display = 'none';
      fetchDecoyList();
    } else {
      tabNewBtn?.classList.add('is-active');
      tabListBtn?.classList.remove('is-active');
      if (panelList) panelList.style.display = 'none';
      if (panelNew) panelNew.style.display = 'block';
    }
  };

  async function fetchDecoyList() {
    const listContainer = document.getElementById('bf-decoy-list-container');
    if (!listContainer) return;

    listContainer.textContent = 'Loading deployed decoys...';

    try {
      const response = await fetch('/api/remediate/get-decoys');
      const data = await response.json();

      listContainer.innerHTML = '';

      if (data.success && data.decoys && data.decoys.length > 0) {
        const table = document.createElement('table');
        table.className = 'bf-fallback-table';
        
        const thead = document.createElement('thead');
        thead.innerHTML = `<tr><th>Email</th><th>Label</th><th>Server</th><th>Deployed</th></tr>`;
        table.appendChild(thead);

        const tbody = document.createElement('tbody');
        data.decoys.forEach(d => {
          const tr = document.createElement('tr');

          const tdEmail = document.createElement('td');
          tdEmail.textContent = d.email || '';
          tr.appendChild(tdEmail);

          const tdLabel = document.createElement('td');
          tdLabel.textContent = d.label || '—';
          tr.appendChild(tdLabel);

          const tdServer = document.createElement('td');
          tdServer.textContent = d.imap_host ? `${d.imap_host}:${d.imap_port || 993}` : 'None';
          tr.appendChild(tdServer);

          const tdDate = document.createElement('td');
          tdDate.textContent = d.created_at || '—';
          tr.appendChild(tdDate);

          tbody.appendChild(tr);
        });
        table.appendChild(tbody);
        listContainer.appendChild(table);
      } else {
        listContainer.textContent = 'No decoy mailboxes have been deployed yet.';
      }
    } catch (e) {
      listContainer.textContent = 'Failed to load decoy list: ' + e.message;
    }
  }

  window.submitDeployDecoyForm = async function (event) {
    event.preventDefault();
    const form = document.getElementById('bf-decoy-deploy-form');
    const msgBox = document.getElementById('bf-decoy-deploy-msg');
    if (!form || !msgBox) return;

    const formData = new FormData(form);
    msgBox.style.display = 'none';

    try {
      const csrfToken = document.querySelector('meta[name="csrf-token"]')?.getAttribute('content') || '';
      const response = await fetch('/api/remediate/deploy-decoy', {
        method: 'POST',
        headers: {
          'X-CSRFToken': csrfToken
        },
        body: formData
      });
      const result = await response.json();

      msgBox.style.display = 'block';
      if (result.success) {
        msgBox.textContent = result.message || 'Decoy deployed successfully.';
        msgBox.style.color = 'var(--bf-good)';
        form.reset();
        setTimeout(() => {
          window.switchDecoyDrawerTab('list');
        }, 1200);
      } else {
        msgBox.textContent = result.error || 'Failed to deploy decoy.';
        msgBox.style.color = 'var(--bf-danger)';
      }
    } catch (e) {
      msgBox.style.display = 'block';
      msgBox.textContent = 'Error: ' + e.message;
      msgBox.style.color = 'var(--bf-danger)';
    }
  };

  window.runDecoyScanNow = async function () {
    const btn = document.getElementById('bf-scan-decoys-btn');
    const output = document.getElementById('bf-decoy-scan-output');
    if (!btn || !output) return;

    btn.disabled = true;
    const originalText = btn.innerHTML;
    btn.innerHTML = `<i class="ti ti-loader-2 spin"></i> Scanning IMAP...`;
    output.style.display = 'block';
    output.textContent = 'Connecting to monitored honeypot servers...';

    try {
      const csrfToken = document.querySelector('meta[name="csrf-token"]')?.getAttribute('content') || '';
      const response = await fetch('/api/remediate/check-decoys', {
        method: 'POST',
        headers: {
          'X-CSRFToken': csrfToken
        }
      });
      const data = await response.json();

      btn.disabled = false;
      btn.innerHTML = originalText;

      if (data.success) {
        output.textContent = `Decoy scan completed: ${data.simulations_caught} simulations caught, ${data.intercepted_threats} external unauthorized threats intercepted.`;
      } else {
        output.textContent = data.error || 'Decoy scan failed.';
      }
    } catch (e) {
      btn.disabled = false;
      btn.innerHTML = originalText;
      output.textContent = 'Error during decoy scan: ' + e.message;
    }
  };

  // ── 5. Micro-Training Refresher Trigger ────────────────────────────────
  window.triggerMicroTrainingRefresher = async function () {
    const btn = document.getElementById('bf-refresher-btn');
    if (!btn || btn.disabled) return;

    btn.disabled = true;
    const originalText = btn.innerHTML;
    btn.innerHTML = `<i class="ti ti-loader-2 spin"></i> Sending...`;

    try {
      const csrfToken = document.querySelector('meta[name="csrf-token"]')?.getAttribute('content') || '';
      const response = await fetch('/remediate/micro-training', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'X-CSRFToken': csrfToken
        }
      });
      const result = await response.json();

      if (result.success) {
        btn.innerHTML = `<i class="ti ti-check"></i> Refresher Sent (${result.sent_count || 0})`;
        btn.style.color = 'var(--bf-good)';
      } else {
        btn.disabled = false;
        btn.innerHTML = originalText;
        alert(result.message || 'Could not send refresher.');
      }
    } catch (e) {
      btn.disabled = false;
      btn.innerHTML = originalText;
      alert('Error triggering refresher: ' + e.message);
    }
  };

  // ── 6. Keyboard Accessibility & Initialization ─────────────────────────
  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape') {
      window.closeDecoyDrawer();
    }
  });

  window.initBriefingFigures = function (reportVal, clickVal) {
    animateFigure('bf-num-report', reportVal, '%');
    animateFigure('bf-num-click', clickVal, '%');
    initChartInteractivity();
  };

  // ── 7. Interactive Chart Point Inspection ─────────────────────────────
  function initChartInteractivity() {
    const points = document.querySelectorAll('.bf-chart-point');
    const legend = document.getElementById('bf-trend-legend');
    const inspectBox = document.getElementById('bf-trend-inspect');
    if (!points.length || !legend || !inspectBox) return;

    points.forEach(pt => {
      function showDetails() {
        const name = pt.getAttribute('data-name') || 'Campaign';
        const date = pt.getAttribute('data-date') || '';
        const rep = pt.getAttribute('data-rep') || '0%';
        const clk = pt.getAttribute('data-clk') || '0%';

        inspectBox.innerHTML = '';
        const strongName = document.createElement('strong');
        strongName.textContent = name;
        inspectBox.appendChild(strongName);

        if (date) {
          const spanDate = document.createElement('span');
          spanDate.textContent = ` (${date}) `;
          spanDate.className = 'bf-inspect-date';
          inspectBox.appendChild(spanDate);
        }

        const spanRep = document.createElement('span');
        spanRep.textContent = `· Report: ${rep} `;
        spanRep.className = 'bf-inspect-rep';
        inspectBox.appendChild(spanRep);

        const spanClk = document.createElement('span');
        spanClk.textContent = `· Click: ${clk}`;
        spanClk.className = 'bf-inspect-clk';
        inspectBox.appendChild(spanClk);

        legend.style.display = 'none';
        inspectBox.style.display = 'inline-flex';
      }

      function hideDetails() {
        legend.style.display = 'flex';
        inspectBox.style.display = 'none';
      }

      pt.addEventListener('mouseenter', showDetails);
      pt.addEventListener('mouseleave', hideDetails);
      pt.addEventListener('focus', showDetails);
      pt.addEventListener('blur', hideDetails);
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initChartInteractivity);
  } else {
    initChartInteractivity();
  }

})();
